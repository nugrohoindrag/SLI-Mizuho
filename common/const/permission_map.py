def permission_key(name):
    key = ''.join(c.lower() if c.isalnum() else '_' for c in name)
    while '__' in key:
        key = key.replace('__', '_')
    return key.strip('_')

def permission_name(key):
    return PERMISSION_MAP.get(key)
